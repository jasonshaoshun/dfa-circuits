"""Figure 2 (Cross-Model Scaling) — by method, with train-mode subfolders.

This version matches your new requirements:
- Titles/axes for per-task recovery figures:
    Title:  Recovery Ratio on [TASK] by Method
    Y:      Faithfulness recovery ratio
- Summary title:
    Mean Recovery Ratio Across Tasks by Method
- Same color scheme for BOTH panels (LLaMA + Qwen): green shades by method.
- Output into 4 subfolders:
    1) zero_shot        (LOO-{task})
    2) in_distribution  (TRAIN-{task})
    3) near_distribution (train=All, if available)
    4) best             (best ctrl=none across all available train_specs for that src/method)

Data sources:
1) Baseline & Gold are read from the table2_summary_<task>.csv files (generated by build_table2_summary.py).
2) Ours for each train-mode is read from evaluation PKLs under results/, following evaluation.sh naming:
     results/{method_base}__kind-diffalign__src-{src}__train-{train_spec}__ctrl-none_{ablation}_{level}/...
   and gold results:
     results/{method_base}_{ablation}_{level}/...
   fileciteturn29file0turn27file4

We still plot BOTH metrics (recovery + gapclosed). Titles/labels are updated to be paper-friendly.
"""

